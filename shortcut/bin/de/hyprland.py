# send_shortcut delivers keys straight to the focused client, bypassing compositor
# binds, so media keys must run their action directly: (command, Lua bind flags).
MEDIA_ACTIONS = {
    "XF86AudioMicMute": ("noctalia msg mic-mute", "{ locked = true }"),
    "XF86AudioMute": ("noctalia msg volume-mute", "{ locked = true }"),
    "XF86AudioLowerVolume": ("noctalia msg volume-down", "{ locked = true, repeating = true }"),
    "XF86AudioRaiseVolume": ("noctalia msg volume-up", "{ locked = true, repeating = true }"),
}

MOD_MAP = {
    "ctrl": "CTRL",
    "control": "CTRL",
    "shift": "SHIFT",
    "alt": "ALT",
    "super": "SUPER",
    "meta": "SUPER",
}


def split_combo(combo_str):
    """
    Split a key combination string into (modifier_tokens, raw_key).
    Safely handles combos where the key itself is '+' (e.g. 'Ctrl + +' or '++').
    """
    s = combo_str.strip()
    if s == "+" or s.endswith("+ +") or s.endswith("++") or (s.endswith("+") and not s.endswith(" +")):
        prefix = s[:-1].rstrip()
        if prefix.endswith("+"):
            prefix = prefix[:-1].rstrip()
        parts = [p.strip() for p in prefix.split("+") if p.strip()]
        return parts, "+"

    parts = [p.strip() for p in s.split("+")]
    return parts[:-1], parts[-1]


def normalize_keysym(raw_key):
    """Normalize a raw key string to a valid XKB keysym name."""
    clean = raw_key.strip()
    norm = clean.lower().replace("_", "").replace(" ", "")
    if norm in KEYSYM_MAP:
        return KEYSYM_MAP[norm]
    if len(clean) == 1:
        return clean.upper()
    return clean.capitalize()


def translate_hyprland_trigger(trigger_str):
    """
    Translate human-readable trigger string to Hyprland key combination string.

    Args:
        trigger_str: e.g. 'Ctrl + Alt + T' or 'Super + ='

    Returns:
        Combined key string, e.g. 'CTRL + ALT + T', 'SUPER + equal'
    """
    mod_tokens, raw_key = split_combo(trigger_str)
    mods = [MOD_MAP[p.lower()] for p in mod_tokens if p.lower() in MOD_MAP]
    key = normalize_keysym(raw_key)
    return " + ".join(mods + [key])


def parse_shortcut_action(action_str):
    """
    Parse human action string (e.g. 'Ctrl + Shift + C', 'Space', 'Ctrl + =') into (mods_str, key_str).

    Returns:
        mods_str: space-separated modifiers, e.g. 'CTRL SHIFT'
        key_str: XKB keysym name, e.g. 'equal'
    """
    mod_tokens, raw_key = split_combo(action_str)
    mods = [MOD_MAP[p.lower()] for p in mod_tokens if p.lower() in MOD_MAP]
    key = normalize_keysym(raw_key)
    return " ".join(mods), key


def generate_lua_code(data):
    """Generate complete keybinds.lua code."""
    lines = [
        "-- AUTOMATICALLY GENERATED BY HYPRLAND SHORTCUT COMPILER. DO NOT EDIT.",
        "-- Source: shortcut/keybinds.json",
        "",
        "local M = {}",
        "",
        "-- Track unbound events during a session to avoid clearing newly-bound rules",
        "-- when multiple mappings exist for the same key combination (e.g. app-specific rules).",
        "local unbound = {}",
        "",
        "-- hl.unbind compares key text (ignoring case and spaces), while hl.bind resolves",
        "-- modifiers, so a bind spelled differently survives unbinding and fires alongside",
        "-- ours. Aliases mirror MODIFIER_NAMES in Hyprland's src/keybinds/Resolver.cpp.",
        "local MOD_ALIAS_GROUPS = {",
        '    { "CTRL", "CONTROL" },',
        '    { "ALT", "MOD1" },',
        '    { "SUPER", "WIN", "LOGO", "MOD4", "META" },',
        "}",
        "",
        "local function mod_aliases(token)",
        "    local upper = string.upper(token)",
        "    for _, group in ipairs(MOD_ALIAS_GROUPS) do",
        "        for _, name in ipairs(group) do",
        "            if name == upper then",
        "                return group",
        "            end",
        "        end",
        "    end",
        "    return { upper }",
        "end",
        "",
        "--- List every spelling of a key combination: all modifier aliases in all orders.",
        '--- @param event string Key combination, e.g. "SUPER + CTRL + Left"',
        "--- @return table List of key combination strings",
        "local function key_spellings(event)",
        "    local tokens = {}",
        '    for token in string.gmatch(event, "[^+]+") do',
        '        tokens[#tokens + 1] = string.match(token, "^%s*(.-)%s*$")',
        "    end",
        "    if #tokens < 2 then",
        "        return { event }",
        "    end",
        "",
        "    local key = table.remove(tokens)",
        "    local spellings = {}",
        "    local function visit(remaining, prefix)",
        "        if #remaining == 0 then",
        "            spellings[#spellings + 1] = prefix .. key",
        "            return",
        "        end",
        "        for i, token in ipairs(remaining) do",
        "            local rest = {}",
        "            for j, other in ipairs(remaining) do",
        "                if j ~= i then",
        "                    rest[#rest + 1] = other",
        "                end",
        "            end",
        "            for _, alias in ipairs(mod_aliases(token)) do",
        '                visit(rest, prefix .. alias .. " + ")',
        "            end",
        "        end",
        "    end",
        '    visit(tokens, "")',
        "    return spellings",
        "end",
        "",
        "--- Rebind a key combination: unbinds every spelling of it on first encounter to avoid",
        "--- conflicts/duplication, then binds the new action with optional flags.",
        '--- @param event string Key combination, e.g. "SUPER + C"',
        "--- @param action any Dispatcher action or handler",
        "--- @param flags table|nil Optional flags, e.g. { repeating = true }",
        "function Rebind(event, action, flags)",
        "    local hl = hl or _G.hl or {}",
        '    if type(hl.unbind) == "function" and not unbound[event] then',
        "        for _, spelling in ipairs(key_spellings(event)) do",
        "            pcall(hl.unbind, spelling)",
        "        end",
        "        unbound[event] = true",
        "    end",
        '    if type(hl.bind) == "function" and action ~= nil then',
        "        if flags ~= nil then",
        "            hl.bind(event, action, flags)",
        "        else",
        "            hl.bind(event, action)",
        "        end",
        "    end",
        "end",
        "",
        "local rebind = Rebind",
        "M.rebind = Rebind",
        "M.Rebind = Rebind",
        "_G.Rebind = Rebind",
        "_G.rebind = Rebind",
        "",
        "function M.setup()",
        "    -- Ensure keyd system service and user mapper are stopped in Hyprland (non-blocking)",
        '    os.execute("systemctl stop keyd.service 2>/dev/null &")',
        '    os.execute("systemctl --user stop keyd-application-mapper.service 2>/dev/null &")',
        "    local hl = hl or _G.hl or {}",
        '    if type(hl.bind) ~= "function" then',
        "        -- Fallback if hl API is not exposed globally",
        "        return",
        "    end",
        "    local dsp = hl.dsp or _G.dsp or {}",
        "",
        "    -- Reset unbound tracker so reloading the module reapplies unbind cleanly",
        "    for k in pairs(unbound) do",
        "        unbound[k] = nil",
        "    end",
        "",
        '    if type(hl) == "table" then',
        "        hl.rebind = Rebind",
        "        hl.Rebind = Rebind",
        "    end",
        "    _G.Rebind = Rebind",
        "    _G.rebind = Rebind",
        "",
        "    local function bind_exec(keys, cmd, flags)",
        '        if type(dsp.exec_cmd) == "function" then',
        "            Rebind(keys, dsp.exec_cmd(cmd), flags)",
        "        end",
        "    end",
        "",
        "    local function bind_focus(keys, direction)",
        '        if type(dsp.focus) == "function" then',
        "            Rebind(keys, dsp.focus({ direction = direction }))",
        "        end",
        "    end",
        "",
        "    local function bind_workspace(keys, target)",
        '        if type(dsp.focus) == "function" then',
        "            Rebind(keys, dsp.focus({ workspace = target }))",
        "        end",
        "    end",
        "",
        "    local function bind_resize(keys, dx, dy)",
        '        if type(dsp.window) == "table" and type(dsp.window.resize) == "function" then',
        "            Rebind(keys, dsp.window.resize({ x = dx, y = dy, relative = true }), { repeating = true })",
        '        elseif type(dsp.resize) == "function" then',
        "            Rebind(keys, dsp.resize({ x = dx, y = dy, relative = true }), { repeating = true })",
        "        end",
        "    end",
        "",
        "    local function match_app(win, pattern)",
        "        if not win then return false end",
        "        local ok, cls = pcall(function()",
        '            return tostring(win.class or win.initialClass or win.initial_class or "")',
        "        end)",
        '        if not ok or not cls or cls == "" then return false end',
        "        return string.find(string.lower(cls), string.lower(pattern), 1, true) ~= nil",
        "    end",
        "",
        "    local function send_to_active(target_mods, target_key)",
        '        if type(dsp.send_shortcut) == "function" then',
        '            local action = dsp.send_shortcut({ mods = target_mods, key = target_key, window = "activewindow" })',
        '            if type(hl.dispatch) == "function" then',
        "                hl.dispatch(action)",
        "            end",
        "        end",
        "    end",
        "",
        "    local function bind_shortcut(keys, target_mods, target_key)",
        '        if type(dsp.send_shortcut) == "function" then',
        '            local param = { mods = target_mods, key = target_key, window = "activewindow" }',
        "            Rebind(keys, dsp.send_shortcut(param))",
        "        end",
        "    end",
        "",
        "    local function bind_contextual(keys, app_rules, fallback)",
        "        Rebind(keys, function()",
        '            local win = type(hl.get_active_window) == "function" and hl.get_active_window() or nil',
        "            for _, rule in ipairs(app_rules) do",
        "                if match_app(win, rule.app) then",
        "                    send_to_active(rule.mods, rule.key)",
        "                    return",
        "                end",
        "            end",
        "            if fallback then",
        "                send_to_active(fallback.mods, fallback.key)",
        "            end",
        "        end)",
        "    end",
        "",
        "    -- ===========================================================",
        "    -- 1. Desktop Actions (App Launching & Window Management)",
        "    -- ===========================================================",
    ]

    # 1. Desktop shortcuts
    for trigger, cfg in data.items():
        if "desktop" in cfg:
            key_combo = translate_hyprland_trigger(trigger)
            desktop = cfg["desktop"]
            action = desktop.get("action")
            desc = cfg.get("description", trigger)

            lines.append(f"    -- {desc}")
            if action == "launch":
                cmd = desktop.get("command", "")
                if not cmd.startswith("uwsm "):
                    cmd = f"uwsm app -- {cmd}"
                lines.append(f'    bind_exec("{key_combo}", "{cmd}")')
            elif action == "focus":
                direction = desktop.get("direction", "").lower()
                lines.append(f'    bind_focus("{key_combo}", "{direction}")')
            elif action == "workspace":
                direction = desktop.get("direction", "").lower()
                target = desktop.get("target") or ("r+1" if direction == "right" else "r-1")
                lines.append(f'    bind_workspace("{key_combo}", "{target}")')
            elif action == "resize":
                direction = desktop.get("direction", "").lower()
                step = int(desktop.get("step", 20))
                if direction == "left":
                    dx, dy = -step, 0
                elif direction == "right":
                    dx, dy = step, 0
                elif direction == "up":
                    dx, dy = 0, -step
                elif direction == "down":
                    dx, dy = 0, step
                else:
                    dx, dy = step, 0
                lines.append(f'    bind_resize("{key_combo}", {dx}, {dy})')
            lines.append("")

    lines.extend([
        "    -- ===========================================================",
        "    -- 2. Contextual Application Hotkeys (sendshortcut)",
        "    -- ===========================================================",
    ])

    # 2. Contextual Application Hotkeys & Global Remappings
    for trigger, cfg in data.items():
        if "apps" in cfg:
            key_combo = translate_hyprland_trigger(trigger)
            desc = cfg.get("description", trigger)
            lines.append(f"    -- {desc} ({trigger})")

            rules_entries = []
            for app_pattern, app_action_str in cfg["apps"].items():
                app_name = app_pattern.strip("*")
                target_mods, target_key = parse_shortcut_action(app_action_str)
                rules_entries.append(
                    f'{{ app = "{app_name}", mods = "{target_mods}", key = "{target_key}" }}'
                )

            rules_str = "{\n        " + ",\n        ".join(rules_entries) + "\n    }"

            if "global" in cfg:
                target_mods, target_key = parse_shortcut_action(cfg["global"])
                fallback_str = f'{{ mods = "{target_mods}", key = "{target_key}" }}'
            else:
                fallback_str = "nil"

            lines.append(f'    bind_contextual("{key_combo}", {rules_str}, {fallback_str})')
            lines.append("")
        elif "global" in cfg:
            key_combo = translate_hyprland_trigger(trigger)
            desc = cfg.get("description", trigger)
            lines.append(f"    -- {desc} ({trigger})")
            target_mods, target_key = parse_shortcut_action(cfg["global"])
            if not target_mods and target_key in MEDIA_ACTIONS:
                cmd, flags = MEDIA_ACTIONS[target_key]
                lines.append(f'    bind_exec("{key_combo}", "{cmd}", {flags})')
            else:
                lines.append(f'    bind_shortcut("{key_combo}", "{target_mods}", "{target_key}")')
            lines.append("")

    lines.extend([
        "end",
        "",
        "return M",
        "",
    ])

    return "\n".join(lines)


def compile(data, workspace_dir):
    """Main compile entrypoint for Hyprland backend."""
    hypr_dir = os.path.join(workspace_dir, "hypr")
    os.makedirs(hypr_dir, exist_ok=True)

    keybind_path = os.path.join(hypr_dir, "keybind.lua")
    lua_code = generate_lua_code(data)
    with open(keybind_path, "w", encoding="utf-8") as f:
        f.write(lua_code)

    init_path = os.path.join(hypr_dir, "init.lua")
    init_code = (
        "-- AUTOMATICALLY GENERATED BY HYPRLAND SHORTCUT COMPILER. DO NOT EDIT.\n"
        "-- Source: shortcut/keybinds.json\n\n"
        "local M = {}\n"
        'local keybind = require("preferences.keybind")\n\n'
        "M.rebind = keybind.rebind\n"
        "M.Rebind = keybind.Rebind\n\n"
        "function M.setup()\n"
        '    if type(keybind.setup) == "function" then\n'
        "        keybind.setup()\n"
        "    end\n"
        "end\n\n"
        "return M\n"
    )
    with open(init_path, "w", encoding="utf-8") as f:
        f.write(init_code)

    legacy_path = os.path.join(workspace_dir, "preferences_keybind.lua")
    if os.path.isfile(legacy_path):
        try:
            os.remove(legacy_path)
        except OSError:
            pass

    print("  -> [hyprland] Generated hypr/init.lua and hypr/keybind.lua")
