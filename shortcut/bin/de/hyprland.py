#!/usr/bin/env python3
# pylint: disable=invalid-name
"""Hyprland desktop environment shortcut compiler.

Generates:
- preferences_keybind.lua: Native Lua configuration module for Hyprland using hl.bind,
  sendshortcut, exec, and movefocus dispatchers.
"""

import os


def translate_hyprland_trigger(trigger_str):
    """
    Translate human-readable trigger string to Lua modifiers array and key string.

    Args:
        trigger_str: e.g. 'Ctrl + Alt + T' or 'Super + C'

    Returns:
        tuple of (lua_mods_str, key_str), e.g. ('{"CTRL", "ALT"}', 'T')
    """
    parts = [p.strip() for p in trigger_str.split("+")]
    mod_map = {
        "ctrl": "CTRL",
        "control": "CTRL",
        "shift": "SHIFT",
        "alt": "ALT",
        "super": "SUPER",
        "meta": "SUPER",
    }
    mods = [mod_map[p.lower()] for p in parts[:-1] if p.lower() in mod_map]
    raw_key = parts[-1]
    if len(raw_key) == 1:
        key = raw_key.upper()
    else:
        key = raw_key.lower()

    mods_lua = "{" + ", ".join(f'"{m}"' for m in mods) + "}"
    return mods_lua, key


def translate_action_hyprland(action_str):
    """
    Translate human action string (e.g. 'Ctrl + Shift + C') to Hyprland shortcut format
    (e.g. 'CONTROL SHIFT, C').
    """
    parts = [p.strip() for p in action_str.split("+")]
    mod_map = {
        "ctrl": "CONTROL",
        "control": "CONTROL",
        "shift": "SHIFT",
        "alt": "ALT",
        "super": "SUPER",
        "meta": "SUPER",
    }
    mods = [mod_map[p.lower()] for p in parts[:-1] if p.lower() in mod_map]
    raw_key = parts[-1]
    if len(raw_key) == 1:
        key = raw_key.upper()
    else:
        key = raw_key.capitalize()

    mods_str = " ".join(mods)
    return f"{mods_str}, {key}"


def app_to_windowrule(app_pattern):
    """Convert app pattern like '*kitty*' to Hyprland class regex 'class:^(kitty)$'."""
    clean = app_pattern.strip("*")
    if clean.lower() == "chrome":
        return "class:^(google-chrome)$"
    return f"class:^({clean})$"


def generate_lua_code(data):
    """Generate complete keybinds.lua code."""
    lines = [
        "-- AUTOMATICALLY GENERATED BY HYPRLAND SHORTCUT COMPILER. DO NOT EDIT.",
        "-- Source: shortcut/keybinds.json",
        "",
        "local M = {}",
        "",
        "function M.setup()",
        "    -- Ensure keyd system service and user mapper are stopped in Hyprland (non-blocking)",
        '    os.execute("systemctl stop keyd.service 2>/dev/null &")',
        '    os.execute("systemctl --user stop keyd-application-mapper.service 2>/dev/null &")',
        "    local hl = hl or _G.hl or {}",
        '    if type(hl.bind) ~= "function" then',
        "        -- Fallback if hl API is not exposed globally",
        "        return",
        "    end",
        "",
        "    -- ===========================================================",
        "    -- 1. Desktop Actions (App Launching & Window Management)",
        "    -- ===========================================================",
    ]

    direction_map = {
        "up": "u",
        "down": "d",
        "left": "l",
        "right": "r",
    }

    # 1. Desktop shortcuts
    for trigger, cfg in data.items():
        if "desktop" in cfg:
            mods_lua, key = translate_hyprland_trigger(trigger)
            desktop = cfg["desktop"]
            action = desktop.get("action")
            desc = cfg.get("description", trigger)

            lines.append(f"    -- {desc}")
            if action == "launch":
                cmd = desktop.get("command", "")
                lines.append(f'    hl.bind({mods_lua}, "{key}", "exec", "{cmd}")')
            elif action == "focus":
                direction = desktop.get("direction", "").lower()
                d_code = direction_map.get(direction, direction)
                lines.append(f'    hl.bind({mods_lua}, "{key}", "movefocus", "{d_code}")')
            lines.append("")

    lines.extend([
        "    -- ===========================================================",
        "    -- 2. Contextual Application Hotkeys (sendshortcut)",
        "    -- ===========================================================",
    ])

    # 2. App-specific shortcuts
    for trigger, cfg in data.items():
        if "apps" in cfg:
            mods_lua, key = translate_hyprland_trigger(trigger)
            desc = cfg.get("description", trigger)
            lines.append(f"    -- {desc} ({trigger})")

            # App-specific mappings first
            for app_pattern, app_action_str in cfg["apps"].items():
                rule = app_to_windowrule(app_pattern)
                hypr_target = translate_action_hyprland(app_action_str)
                lines.append(f'    hl.bind({mods_lua}, "{key}", "sendshortcut", "{hypr_target}, {rule}")')

            # Global fallback mapping
            if "global" in cfg:
                hypr_global = translate_action_hyprland(cfg["global"])
                lines.append(f'    hl.bind({mods_lua}, "{key}", "sendshortcut", "{hypr_global}")')
            lines.append("")

    lines.extend([
        "end",
        "",
        "return M",
        "",
    ])

    return "\n".join(lines)


def compile(data, workspace_dir):
    """Main compile entrypoint for Hyprland backend."""
    lua_path = os.path.join(workspace_dir, "preferences_keybind.lua")
    lua_code = generate_lua_code(data)

    with open(lua_path, "w", encoding="utf-8") as f:
        f.write(lua_code)

    print("  -> [hyprland] Generated preferences_keybind.lua")
