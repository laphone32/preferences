#!/usr/bin/env python3
# pylint: disable=invalid-name
"""GNOME & keyd desktop environment shortcut compiler.

Generates:
- default.conf: global evdev remappings for keyd
- app.conf: per-application evdev remappings for keyd-application-mapper
- gnome-shortcuts.sh: GNOME gsettings shell script for custom media keys & window focus
"""

import os
import re


def translate_layer(trigger_str):
    """Translate trigger string to keyd layer and key for global mappings."""
    parts = [p.strip().lower() for p in trigger_str.split("+")]
    mod_map = {
        "ctrl": "control",
        "shift": "shift",
        "alt": "alt",
        "super": "meta",
    }
    mods = [mod_map[p] for p in parts[:-1] if p in mod_map]
    key = parts[-1]
    layer_name = "-".join(mods)
    return layer_name, key


def translate_app_layer(trigger_str):
    """Translate trigger string to keyd layer binding format for app.conf."""
    parts = [p.strip().lower() for p in trigger_str.split("+")]
    mod_map = {"ctrl": "C", "shift": "S", "alt": "A", "super": "meta"}
    mods = [mod_map[p] for p in parts[:-1] if p in mod_map]
    key = parts[-1]
    if mods:
        return "-".join(mods) + "." + key
    return key


def translate_action(action_str):
    """Translate human-readable action string to keyd RHS action string."""
    parts = [p.strip().lower() for p in action_str.split("+")]
    mod_map = {"ctrl": "C", "shift": "S", "alt": "A", "super": "M"}
    mods = [mod_map[p] for p in parts[:-1] if p in mod_map]
    key = parts[-1]
    if mods:
        return "-".join(mods) + "-" + key
    return key


def translate_gnome_trigger(trigger_str):
    """Translate trigger string to GNOME accelerator format."""
    parts = [p.strip() for p in trigger_str.split("+")]
    mod_map = {
        "ctrl": "<Control>",
        "control": "<Control>",
        "shift": "<Shift>",
        "alt": "<Alt>",
        "super": "<Super>",
        "meta": "<Super>",
    }
    mods = [mod_map[p.lower()] for p in parts[:-1] if p.lower() in mod_map]
    raw_key = parts[-1]
    if len(raw_key) == 1:
        key = raw_key.lower()
    else:
        key = raw_key.capitalize()
    return "".join(mods) + key


def generate_gnome_script(desktop_entries):
    """Generate GNOME gsettings shell script for applying shortcuts."""
    lines = [
        "#!/usr/bin/env bash",
        "# AUTOMATICALLY GENERATED BY GNOME SHORTCUT COMPILER. DO NOT EDIT.",
        "# Source: shortcut/keybinds.json",
        "set -euo pipefail",
        "",
        "if ! command -v gsettings &>/dev/null; then",
        '    echo "gsettings not available, skipping GNOME shortcut configuration."',
        "    exit 0",
        "fi",
        "",
        "# Helper to add custom media-keys keybinding idempotently",
        "set_gnome_custom_keybinding() {",
        '    local name="$1"',
        '    local command="$2"',
        '    local binding="$3"',
        '    local slug="$4"',
        '    local path="/org/gnome/settings-daemon/plugins/media-keys/custom-keybindings/$slug/"',
        "",
        "    local current",
        '    current=$(gsettings get org.gnome.settings-daemon.plugins.media-keys custom-keybindings 2>/dev/null || echo "@as []")',
        '    if [ "$current" == "@as []" ] || [ -z "$current" ]; then',
        '        gsettings set org.gnome.settings-daemon.plugins.media-keys custom-keybindings "[\'$path\']"',
        '    elif [[ "$current" != *"$path"* ]]; then',
        '        local updated="${current%]*}, \'$path\']"',
        '        gsettings set org.gnome.settings-daemon.plugins.media-keys custom-keybindings "$updated"',
        "    fi",
        "",
        '    gsettings set "org.gnome.settings-daemon.plugins.media-keys.custom-keybinding:$path" name "$name"',
        '    gsettings set "org.gnome.settings-daemon.plugins.media-keys.custom-keybinding:$path" command "$command"',
        '    gsettings set "org.gnome.settings-daemon.plugins.media-keys.custom-keybinding:$path" binding "$binding"',
        "}",
        "",
        'echo "Applying GNOME desktop shortcuts..."',
        "",
    ]

    for trigger, cfg in desktop_entries:
        gnome_accel = translate_gnome_trigger(trigger)
        desktop = cfg["desktop"]
        action = desktop.get("action")
        desc = cfg.get("description", trigger)

        if action == "launch":
            cmd = desktop.get("command", "")
            slug = re.sub(r"[^a-zA-Z0-9_-]", "-", trigger.lower()).strip("-")
            lines.append(f"# {desc}")
            lines.append(f'set_gnome_custom_keybinding "{desc}" "{cmd}" "{gnome_accel}" "{slug}"')
            lines.append("")
        elif action == "focus":
            direction = desktop.get("direction", "").lower()
            lines.append(f"# {desc}")
            if direction == "up":
                lines.append('if gsettings list-schemas | grep -q "org.gnome.shell.extensions.pop-shell"; then')
                lines.append(f'    gsettings set org.gnome.shell.extensions.pop-shell focus-up "[\'{gnome_accel}\']" 2>/dev/null || true')
                lines.append("fi")
                lines.append(f'gsettings set org.gnome.desktop.wm.keybindings switch-windows-backward "[\'{gnome_accel}\']" 2>/dev/null || true')
            elif direction == "down":
                lines.append('if gsettings list-schemas | grep -q "org.gnome.shell.extensions.pop-shell"; then')
                lines.append(f'    gsettings set org.gnome.shell.extensions.pop-shell focus-down "[\'{gnome_accel}\']" 2>/dev/null || true')
                lines.append("fi")
                lines.append(f'gsettings set org.gnome.desktop.wm.keybindings switch-windows "[\'{gnome_accel}\']" 2>/dev/null || true')
            elif direction == "left":
                lines.append('if gsettings list-schemas | grep -q "org.gnome.shell.extensions.pop-shell"; then')
                lines.append(f'    gsettings set org.gnome.shell.extensions.pop-shell focus-left "[\'{gnome_accel}\']" 2>/dev/null || true')
                lines.append("fi")
            elif direction == "right":
                lines.append('if gsettings list-schemas | grep -q "org.gnome.shell.extensions.pop-shell"; then')
                lines.append(f'    gsettings set org.gnome.shell.extensions.pop-shell focus-right "[\'{gnome_accel}\']" 2>/dev/null || true')
                lines.append("fi")
            lines.append("")
        elif action == "workspace":
            direction = desktop.get("direction", "").lower()
            lines.append(f"# {desc}")
            if direction == "left":
                lines.append(f'gsettings set org.gnome.desktop.wm.keybindings switch-to-workspace-left "[\'{gnome_accel}\']" 2>/dev/null || true')
            elif direction == "right":
                lines.append(f'gsettings set org.gnome.desktop.wm.keybindings switch-to-workspace-right "[\'{gnome_accel}\']" 2>/dev/null || true')
            lines.append("")
        elif action == "resize":
            direction = desktop.get("direction", "").lower()
            lines.append(f"# {desc}")
            if direction == "left":
                lines.append('if gsettings list-schemas | grep -q "org.gnome.shell.extensions.pop-shell"; then')
                lines.append(f'    gsettings set org.gnome.shell.extensions.pop-shell tile-resize-left "[\'{gnome_accel}\']" 2>/dev/null || true')
                lines.append("fi")
            elif direction == "right":
                lines.append('if gsettings list-schemas | grep -q "org.gnome.shell.extensions.pop-shell"; then')
                lines.append(f'    gsettings set org.gnome.shell.extensions.pop-shell tile-resize-right "[\'{gnome_accel}\']" 2>/dev/null || true')
                lines.append("fi")
            lines.append("")

    lines.append('echo "GNOME desktop shortcuts applied successfully."')
    lines.append("")
    return "\n".join(lines)


def compile(data, workspace_dir):
    """Main compile entrypoint for GNOME & keyd backend."""
    default_conf_path = os.path.join(workspace_dir, "default.conf")
    app_conf_path = os.path.join(workspace_dir, "app.conf")
    gnome_sh_path = os.path.join(workspace_dir, "gnome-shortcuts.sh")

    default_layers = {}
    apps_dict = {}
    desktop_entries = []

    for trigger, cfg in data.items():
        if "global" in cfg:
            layer, key = translate_layer(trigger)
            action = translate_action(cfg["global"])
            if layer not in default_layers:
                default_layers[layer] = []
            default_layers[layer].append(f"{key} = {action}")

        if "apps" in cfg:
            app_lhs = translate_app_layer(trigger)
            for app_name, app_action_str in cfg["apps"].items():
                action = translate_action(app_action_str)
                if app_name not in apps_dict:
                    apps_dict[app_name] = []
                apps_dict[app_name].append(f"{app_lhs} = {action}")

        if "desktop" in cfg:
            desktop_entries.append((trigger, cfg))

    # Write default.conf
    default_lines = [
        "# AUTOMATICALLY GENERATED. DO NOT EDIT.",
        "[ids]",
        "*",
        "",
        "[main]",
        "",
    ]
    for layer, binds in default_layers.items():
        default_lines.append(f"[{layer}]")
        for bind in binds:
            default_lines.append(bind)
        default_lines.append("")

    with open(default_conf_path, "w", encoding="utf-8") as f:
        f.write("\n".join(default_lines))

    # Write app.conf
    app_lines = [
        "# AUTOMATICALLY GENERATED. DO NOT EDIT.",
        "",
    ]
    for app_name, binds in apps_dict.items():
        app_lines.append(f"[{app_name}]")
        for bind in binds:
            app_lines.append(bind)
        app_lines.append("")

    with open(app_conf_path, "w", encoding="utf-8") as f:
        f.write("\n".join(app_lines))

    # Write gnome-shortcuts.sh if desktop entries exist
    if desktop_entries:
        gnome_script = generate_gnome_script(desktop_entries)
        with open(gnome_sh_path, "w", encoding="utf-8") as f:
            f.write(gnome_script)
        os.chmod(gnome_sh_path, 0o755)

    print("  -> [gnome] Generated default.conf, app.conf, gnome-shortcuts.sh")
